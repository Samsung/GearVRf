/***************************************************************************
 * Class containing light source parameters.
 ***************************************************************************/

#ifndef LIGHT_H_
#define LIGHT_H_

#include <map>
#include <memory>
#include <string>

#include "glm/glm.hpp"

#include "objects/hybrid_object.h"

namespace gvr {
class Color;
class SceneObject;

class Light: public HybridObject {
public:
    explicit Light()
    :   enabled_(true),
        dirty_(false),
        parent_(NULL) {
    }

    ~Light() {
    }

    bool enabled() {
        return enabled_;
    }

    void enable() {
        enabled_ = true;
        dirty_ = true;
    }

    void disable() {
        enabled_ = false;
    }

    float getFloat(std::string key) {
        auto it = floats_.find(key);
        if (it != floats_.end()) {
            return it->second;
        } else {
            std::string error = "Light::getFloat() : " + key + " not found";
            throw error;
        }
    }

    void setFloat(std::string key, float value) {
        if (getOffset(key) < 0)
            offsets_[key] = floats_.size();
        floats_[key] = value;
        if (enabled_) {
            dirty_ = true;
        }
    }

    glm::vec3 getVec3(std::string key) {
        auto it = vec3s_.find(key);
        if (it != vec3s_.end()) {
            return it->second;
        } else {
            std::string error = "Light::getVec3() : " + key + " not found";
            throw error;
        }
    }

    void setVec3(std::string key, glm::vec3 vector) {
        vec3s_[key] = vector;
        if (enabled_) {
            dirty_ = true;
        }
    }

    glm::vec4 getVec4(std::string key) {
        auto it = vec4s_.find(key);
        if (it != vec4s_.end()) {
            return it->second;
        } else {
            std::string error = "Light::getVec4() : " + key + " not found";
            throw error;
        }
    }

    void setVec4(std::string key, glm::vec4 vector) {
        vec4s_[key] = vector;
        if (enabled_) {
            dirty_ = true;
        }
    }

    /**
     * Internal function called at the start of each frame
     * to update the light uniform block (if necessary).
     * @param program    ID of GL shader program
     */
    void render(int program);

    /**
     * Get the GVRSceneObject this light is attached to.
     *
     * If a light is attached to a scene object, its position
     * and direction are obtained from the scene object's transform.
     */
    SceneObject* parent() { return parent_; }

    /**
     * Attach this light to a scene object.
     *
     * Its position and direction are obtained from the scene object's transform.
     */
    void setParent(SceneObject* parent) {
        parent_ = parent;
    }

    std::string getLightID() {
        return lightID_;
    }

     /**
     * Set the light ID. This is a string that uniquely
     * identifies this light. This ID is generated by
     * GVRScene when the light is attached.
     * {@link GVRScene.addLight }
     */
    void setLightID(std::string lightid) {
        lightID_ = lightid;
    };

private:
    Light(const Light& light);
    Light(Light&& light);
    Light& operator=(const Light& light);
    Light& operator=(Light&& light);

    /*
     * Get the GL uniform offset for a named uniform.
     */
    int getOffset(std::string key) {
        auto it = offsets_.find(key);
        if (it != offsets_.end()) {
            return it->second;
        } else {
            return -1;
        }
    }

private:
    bool enabled_;
    bool dirty_;
    int size_;
    std::string lightID_;
    SceneObject* parent_;
    std::map<std::string, float> floats_;
    std::map<std::string, glm::vec3> vec3s_;
    std::map<std::string, glm::vec4> vec4s_;
    std::map<std::string, int> offsets_;

};
}
#endif
