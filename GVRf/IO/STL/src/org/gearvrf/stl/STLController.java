package org.gearvrf.stl;

import java.util.HashSet;
import java.util.Set;

import android.content.Context;
import android.hardware.input.InputManager;
import android.hardware.input.InputManager.InputDeviceListener;
import android.util.Log;
import android.view.InputDevice;
import android.view.KeyEvent;
import android.view.MotionEvent;

/**
 * Use this class to translate MotionEvents and KeyEvents generated by the
 * controller to values that can be used to create InputEvents for the GVRf
 * GVRInputManager.
 */
public class STLController implements InputDeviceListener {
    private static final String TAG = STLController.class.getSimpleName();
    private static final int DELAY_MILLISECONDS = 16;

    private final EventHandlerThread thread;
    private final InputManager inputManager;
    private final ControllerListener listener;
    private Set<Integer> deviceIds = new HashSet<>();

    public interface ControllerListener {
        /**
         * This method is called whenever an Event is passed to the
         * {@link STLController} class.
         * 
         * Note that this call happens on the EventHandlerThread.
         * 
         * @param id
         *            id of the device that generated this callback
         * @param x
         *            returns the joystick displacement along the x axis
         * @param y
         *            returns the joystick displacement along the y axis
         * @param z
         *            returns the joystick displacement along the z axis
         * @param active
         *            returns <code>true</code> on button press and
         *            <code>false</code> on release
         */
        public void onEvent(int id, float x, float y, float z, boolean active);

        /**
         * Report the id of the controller/joystick device attached to the app.
         * 
         * @param id
         */
        public void onControllerAdded(int id);

        /**
         * Notify the app that a controller/joystick device has been detached.
         * 
         * @param id
         */
        public void onControllerRemoved(int id);
    }

    /**
     * STLController is a helper class that can be used to receive continuous x,
     * y and z coordinate updates for a controller or a joystick device that is
     * used with an Android device.
     * 
     * The main functions of this helper class are <br>
     * 
     * 1) To provide a separate thread to handle all the input events generated
     * by Android. This ensures that the main UI thread is not blocked while
     * performing GVRf actions. <br>
     * 
     * 2) Provide x, y, and z displacement values to the App. <br>
     * 
     * 3) Provide a notification whenever a new device is added or removed by
     * the user.
     * 
     * @param context
     *            The Android application context
     * @param listener
     *            The callback method that delivers all the information back to
     *            the app.
     * @param activeButtons
     *            The list os all the buttons that will trigger the active
     *            pressed state of the controllers.<br>
     *            eg. use new int[] { KeyEvent.KEYCODE_BUTTON_A,
     *            KeyEvent.KEYCODE_BUTTON_B} to use button A and B as active
     *            buttons.
     * 
     * 
     */
    public STLController(Context context, ControllerListener listener,
            int[] activeButtons) {
        inputManager = (InputManager) context
                .getSystemService(Context.INPUT_SERVICE);
        inputManager.registerInputDeviceListener(this, null);
        this.listener = listener;
        for (int deviceId : inputManager.getInputDeviceIds()) {
            if (isControllerDevice(deviceId)) {
                deviceIds.add(deviceId);
                listener.onControllerAdded(deviceId);
            }
        }
        thread = new EventHandlerThread("EventHandlerThread", listener,
                activeButtons);
        thread.start();
    }

    public void close() {
        deviceIds.clear();
        thread.interrupt();
    }

    public boolean dispatchKeyEvent(KeyEvent event) {
        if ((thread.isActive == false
                && event.getAction() == KeyEvent.ACTION_DOWN)
                || (thread.isActive == true
                        && event.getAction() == KeyEvent.ACTION_UP)) {
            return thread.submitKeyEvent(event);
        }
        return true;
    }

    public boolean dispatchMotionEvent(MotionEvent event) {
        MotionEvent clone = MotionEvent.obtain(event);
        return thread.submitMotionEvent(clone);
    }

    private class EventHandlerThread extends Thread {
        private final Set<Integer> activeButtons;
        private int dpadState;
        private boolean isActive = false;
        private float x, y, ry;
        private Object lock = new Object();
        private MotionEvent event;
        private KeyEvent keyEvent;
        private boolean pedalDown = false;
        private int id;

        EventHandlerThread(String name, ControllerListener listener,
                int[] activeButtons) {
            super(name);
            this.activeButtons = new HashSet<Integer>();
            for (int button = 0; button < activeButtons.length; button++) {
                this.activeButtons.add(activeButtons[button]);
            }
        }

        @Override
        public void run() {
            try {
                while (true) {
                    boolean running = false;
                    synchronized (lock) {
                        if (event == null && keyEvent == null) {
                            lock.wait();
                        }
                        if (event != null) {
                            running = dispatchMotionEvent(event);
                            if (running == false) {
                                event.recycle();
                                event = null;
                            }
                        }
                        if (keyEvent != null) {
                            dispatchKeyEvent(keyEvent);
                            keyEvent = null;
                        }
                        listener.onEvent(this.id, this.x, this.y, this.ry,
                                isActive);
                    }
                    Thread.sleep(DELAY_MILLISECONDS);
                }
            } catch (InterruptedException e) {
                e.printStackTrace();
            }
        }

        private void dispatchKeyEvent(KeyEvent event) {
            int keyCode = event.getKeyCode();
            int action = event.getAction();
            id = event.getDeviceId();
            if (id != -1) {
                if (activeButtons.contains(keyCode)) {
                    if (action == KeyEvent.ACTION_DOWN && isActive == false) {
                        isActive = true;
                    } else
                        if (action == KeyEvent.ACTION_UP && isActive == true) {
                        isActive = false;
                    }
                } else {
                    switch (keyCode) {
                    case KeyEvent.KEYCODE_DPAD_LEFT:
                        if (action == KeyEvent.ACTION_DOWN
                                && dpadState != KeyEvent.KEYCODE_DPAD_LEFT) {
                            dpadState = KeyEvent.KEYCODE_DPAD_LEFT;

                            x = -1.0f;
                        } else if (action == KeyEvent.ACTION_UP) {
                            dpadState = 0;
                        }
                        break;
                    case KeyEvent.KEYCODE_DPAD_RIGHT:
                        if (action == KeyEvent.ACTION_DOWN
                                && dpadState != KeyEvent.KEYCODE_DPAD_RIGHT) {
                            dpadState = KeyEvent.KEYCODE_DPAD_RIGHT;
                            x = 1.0f;
                        } else if (action == KeyEvent.ACTION_UP) {
                            dpadState = 0;
                        }
                        break;
                    case KeyEvent.KEYCODE_DPAD_UP:
                        if (action == KeyEvent.ACTION_DOWN
                                && dpadState != KeyEvent.KEYCODE_DPAD_UP) {
                            dpadState = KeyEvent.KEYCODE_DPAD_UP;
                            y = 1.0f;
                        } else if (action == KeyEvent.ACTION_UP) {
                            dpadState = 0;
                        }
                        break;
                    case KeyEvent.KEYCODE_DPAD_DOWN:
                        if (action == KeyEvent.ACTION_DOWN
                                && dpadState != KeyEvent.KEYCODE_DPAD_DOWN) {
                            dpadState = KeyEvent.KEYCODE_DPAD_DOWN;
                            y = -1.0f;
                        } else if (action == KeyEvent.ACTION_UP) {
                            dpadState = 0;
                        }
                        break;
                    }

                }
            }
        }

        boolean submitMotionEvent(MotionEvent event) {
            if (event.isFromSource(InputDevice.SOURCE_GAMEPAD)
                    || event.isFromSource(InputDevice.SOURCE_JOYSTICK)) {
                MotionEvent clone = MotionEvent.obtain(event);

                synchronized (lock) {
                    if (event != null) {
                        event.recycle();
                    }
                    this.event = clone;
                    lock.notify();
                }

                return true;
            } else {
                return false;
            }
        }

        boolean submitKeyEvent(KeyEvent event) {
            synchronized (lock) {
                keyEvent = event;
                lock.notify();
            }
            return true;
        }

        // The following methods are taken from the controller sample on the
        // Android Developer web site:
        // https://developer.android.com/training/game-controllers/controller-input.html
        private boolean dispatchMotionEvent(MotionEvent event) {
            if (event.getAction() == MotionEvent.ACTION_MOVE) {
                id = event.getDeviceId();
                if (id != -1) {
                    return processJoystickInput(event);
                }
            }
            return false;
        }

        private boolean processJoystickInput(MotionEvent event) {
            InputDevice device = event.getDevice();
            float x = getCenteredAxis(event, device, MotionEvent.AXIS_X);
            if (x == 0) {
                x = getCenteredAxis(event, device, MotionEvent.AXIS_HAT_X);
            }

            float y = getCenteredAxis(event, device, MotionEvent.AXIS_Y);
            if (y == 0) {
                y = getCenteredAxis(event, device, MotionEvent.AXIS_HAT_Y);
            }

            float ry = 0.0f;
            int vendorId = device.getVendorId();
            int productId = device.getProductId();

            if (vendorId == STLConstants.SAMSUNG_GAMEPAD_VENDOR_ID
                    && productId == STLConstants.SAMSUNG_GAMEPAD_PRODUCT_ID) {
                ry = getCenteredAxis(event, device, MotionEvent.AXIS_RY);
            } else
                if ((vendorId == STLConstants.SONY_DUALSHOCK_CONTROLLER_VENDOR_ID
                        && (productId == STLConstants.SONY_DUALSHOCK_3_CONTROLLER_PRODUCT_ID
                                || productId == STLConstants.SONY_DUALSHOCK_4_CONTROLLER_PRODUCT_ID))) {
                ry = getCenteredAxis(event, device, MotionEvent.AXIS_RZ);
            } else if ((vendorId == STLConstants.STEELSERIES_CONTROLLER_VENDOR_ID
                    && productId == STLConstants.STEELSERIES_CONTROLLER_PRODUCT_ID)) {
                ry = getCenteredAxis(event, device, MotionEvent.AXIS_RZ);
                if ((getCenteredAxis(event, device, MotionEvent.AXIS_BRAKE) != 0
                        || getCenteredAxis(event, device,
                                MotionEvent.AXIS_GAS) != 0)
                        && pedalDown == false) {
                    pedalDown = true;
                    if (isActive == false) {
                        isActive = true;
                    }
                } else if ((getCenteredAxis(event, device,
                        MotionEvent.AXIS_BRAKE) == 0
                        && getCenteredAxis(event, device,
                                MotionEvent.AXIS_GAS) == 0)
                        && pedalDown == true) {
                    pedalDown = false;
                    if (isActive == true) {
                        isActive = false;
                    }
                }
            }

            this.x = x;
            this.y = -y;
            this.ry = ry;

            if (x == 0 && y == 0 && ry == 0) {
                return false;
            } else {
                return true;
            }
        }

        private float getCenteredAxis(MotionEvent event, InputDevice device,
                int axis) {
            final InputDevice.MotionRange range = device.getMotionRange(axis,
                    event.getSource());
            if (range != null) {
                final float flat = range.getFlat();
                final float value = event.getAxisValue(axis);
                if (Math.abs(value) > flat) {
                    return value;
                }
            }
            return 0;
        }
    }

    private boolean isControllerDevice(int deviceId) {
        InputDevice device = inputManager.getInputDevice(deviceId);
        if (device != null) {
            return ((device.getSources()
                    & InputDevice.SOURCE_GAMEPAD) == InputDevice.SOURCE_GAMEPAD
                    || (device.getSources()
                            & InputDevice.SOURCE_JOYSTICK) == InputDevice.SOURCE_JOYSTICK);
        } else {
            return false;
        }
    }

    @Override
    public void onInputDeviceAdded(int deviceId) {
        Log.d(TAG, "onInputDeviceAdded " + deviceId);
        if (isControllerDevice(deviceId)) {
            deviceIds.add(deviceId);
            listener.onControllerAdded(deviceId);
        }
    }

    @Override
    public void onInputDeviceChanged(int deviceId) {
        // Not Used
    }

    @Override
    public void onInputDeviceRemoved(int deviceId) {
        Log.d(TAG, "onInputDeviceRemoved " + deviceId);
        if (deviceIds.contains(deviceId)) {
            deviceIds.remove(deviceId);
            listener.onControllerRemoved(deviceId);
        }

    }
}
